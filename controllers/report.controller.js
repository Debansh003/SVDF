// ============================================================
// controllers/report.controller.js — Security Report Generation
// ============================================================
const path      = require('path');
const fs        = require('fs');
const zlib      = require('zlib');
const Report    = require('../models/report.model');
const AttackLog = require('../models/attackLog.model');
const Alert     = require('../models/alert.model');
const os        = require('os');

// POST /api/v1/reports/generate
const generateReport = async (req, res) => {
  try {
    const { title = 'Security Report', type = 'full' } = req.body;

    const [attacks, alerts, stats] = await Promise.all([
      AttackLog.find().sort({ createdAt: -1 }).limit(100),
      Alert.find().sort({ createdAt: -1 }).limit(50),
      AttackLog.aggregate([{ $group: { _id: '$severity', count: { $sum: 1 } } }])
    ]);

    const statsObj = {};
    stats.forEach(s => { statsObj[s._id] = s.count; });

    const reportContent = `
================================================================================
                    OS SECURITY VULNERABILITY DETECTION FRAMEWORK
                              SECURITY REPORT
================================================================================
Report Title:   ${title}
Report Type:    ${type.toUpperCase()}
Generated At:   ${new Date().toISOString()}
Generated By:   ${req.user?.username || 'System'}
Platform:       ${os.platform()} / ${os.arch()}
Hostname:       ${os.hostname()}
================================================================================

EXECUTIVE SUMMARY
-----------------
Total Attacks Simulated:  ${attacks.length}
Total Alerts Generated:   ${alerts.length}
Unread Alerts:            ${alerts.filter(a=>!a.isRead).length}
Critical Incidents:       ${statsObj.CRITICAL || 0}
High Severity:            ${statsObj.HIGH || 0}
Medium Severity:          ${statsObj.MEDIUM || 0}
Low Severity:             ${statsObj.LOW || 0}

SYSTEM INFORMATION
------------------
CPU Cores:    ${os.cpus().length}
Total Memory: ${(os.totalmem()/(1024**3)).toFixed(2)} GB
Free Memory:  ${(os.freemem()/(1024**3)).toFixed(2)} GB
Uptime:       ${(os.uptime()/3600).toFixed(2)} hours
Node.js:      ${process.version}

ATTACK LOG (Last 20)
---------------------
${attacks.slice(0, 20).map((a, i) =>
  `${i+1}. [${a.severity}] ${a.attackType} — ${a.status} — ${a.target} — ${new Date(a.createdAt).toLocaleString()}`
).join('\n')}

SECURITY RECOMMENDATIONS
-------------------------
1. Implement ASLR and DEP/NX bit to prevent code injection attacks
2. Enable DNSSEC to prevent cache poisoning attacks
3. Apply least-privilege principle across all processes and users
4. Use IDS/IPS systems for real-time threat detection
5. Keep all software, OS, and security patches up to date
6. Implement multi-factor authentication for all privileged access
7. Conduct regular security audits and penetration testing
8. Maintain offline backups with the 3-2-1 backup strategy
9. Enable comprehensive audit logging (auditd, syslog)
10. Deploy endpoint detection and response (EDR) solutions

PREVENTION STATUS BY SEVERITY
-------------------------------
CRITICAL (${statsObj.CRITICAL || 0} incidents): Immediate action required
HIGH     (${statsObj.HIGH || 0} incidents): Action required within 24 hours
MEDIUM   (${statsObj.MEDIUM || 0} incidents): Action required within 1 week
LOW      (${statsObj.LOW || 0} incidents): Action required within 1 month

================================================================================
                        END OF REPORT
================================================================================
`.trim();

    // Save compressed report to disk
    const reportsDir = path.join(__dirname, '..', 'reports');
    if (!fs.existsSync(reportsDir)) fs.mkdirSync(reportsDir, { recursive: true });

    const fileName = `report_${Date.now()}.txt.gz`;
    const filePath = path.join(reportsDir, fileName);
    const compressed = zlib.gzipSync(Buffer.from(reportContent, 'utf8'));
    fs.writeFileSync(filePath, compressed);

    const report = await Report.create({
      title,
      type,
      content:     reportContent,
      filePath:    fileName,
      fileSize:    compressed.length,
      generatedBy: req.user._id,
      stats: {
        totalAttacks: attacks.length,
        totalAlerts:  alerts.length,
        bySeverity:   statsObj
      }
    });

    res.json({ success: true, data: report });
  } catch (err) {
    res.status(500).json({ success: false, message: err.message });
  }
};

// GET /api/v1/reports
const getReports = async (req, res) => {
  try {
    const reports = await Report.find().sort({ createdAt: -1 }).populate('generatedBy', 'username');
    res.json({ success: true, data: reports });
  } catch (err) {
    res.status(500).json({ success: false, message: err.message });
  }
};

// GET /api/v1/reports/:id
const getReportById = async (req, res) => {
  try {
    const report = await Report.findById(req.params.id).populate('generatedBy', 'username email');
    if (!report) return res.status(404).json({ success: false, message: 'Report not found' });
    res.json({ success: true, data: report });
  } catch (err) {
    res.status(500).json({ success: false, message: err.message });
  }
};

// DELETE /api/v1/reports/:id  (admin only)
const deleteReport = async (req, res) => {
  try {
    const report = await Report.findById(req.params.id);
    if (!report) return res.status(404).json({ success: false, message: 'Report not found' });

    // Delete file
    if (report.filePath) {
      const filePath = path.join(__dirname, '..', 'reports', report.filePath);
      if (fs.existsSync(filePath)) fs.unlinkSync(filePath);
    }

    await report.deleteOne();
    res.json({ success: true, message: 'Report deleted' });
  } catch (err) {
    res.status(500).json({ success: false, message: err.message });
  }
};

module.exports = { generateReport, getReports, getReportById, deleteReport };
